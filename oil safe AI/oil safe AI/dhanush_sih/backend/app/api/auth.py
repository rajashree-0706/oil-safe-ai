@router.get("/me", response_model=UserResponse)
def get_me(current_user: User = Depends(get_current_user)):
    return current_user

@router.get("/switch-role/{role}", response_model=Token)
def switch_role(role: str, db: Session = Depends(get_db)):
    """Allows instant role switching during safety operations / evaluation."""
    user = db.query(User).filter(User.role == role).first()
    if not user:
        user = db.query(User).first()
    access_token = create_access_token(data={"sub": user.username, "role": user.role, "user_id": user.id})
    return {
        "access_token": access_token,
        "token_type": "bearer",
        "role": user.role,
        "user_id": user.id,
        "full_name": user.full_name,
        "username": user.username,
        "department": user.department
    }
